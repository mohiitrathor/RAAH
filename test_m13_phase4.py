    # -----------------------------------------------------------------
    # 12. Unauthorized role is rejected if applicable (403)
    # -----------------------------------------------------------------
    def test_12_unauthorized_role_rejected_403(self):
        """When an authenticated user lacks the required permission, endpoint returns 403."""
        self.client.post("/dispatch/1", headers={"Authorization": f"Bearer {self.admin_token}"})
        rec = evidence_store.get_by_incident(1)[0]

        import api.auth.models
        with patch.dict(api.auth.models.PERMISSION_ROLES, {Permission.VIEW_LIVE: {Role.ADMINISTRATOR}}):
            # Dispatcher should now receive 403 Forbidden
            resp = self.client.get(
                f"/decision-evidence/{rec.evidence_id}",
                headers={"Authorization": f"Bearer {self.dispatcher_token}"},
            )
            self.assertEqual(resp.status_code, 403)
            data = resp.json()
            self.assertIn("Forbidden", data.get("detail", ""))

            # Administrator should still succeed with 200
            resp_admin = self.client.get(
                f"/decision-evidence/{rec.evidence_id}",
                headers={"Authorization": f"Bearer {self.admin_token}"},
            )
            self.assertEqual(resp_admin.status_code, 200)

