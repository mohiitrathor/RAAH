    # -----------------------------------------------------------------
    # 17. Explanation API latency is lightweight (<15ms)
    # -----------------------------------------------------------------
    def test_17_explanation_api_latency_lightweight(self):
        """Explanation API lookups must be lightweight in-memory operations (mean < 15ms)."""
        self.client.post("/dispatch/1", headers={"Authorization": f"Bearer {self.admin_token}"})
        rec = evidence_store.get_by_incident(1)[0]

        # Warmup
        self.client.get(f"/decision-evidence/{rec.evidence_id}", headers=self.headers)

        latencies = []
        for _ in range(50):
            start = time.perf_counter()
            r = self.client.get(f"/decision-evidence/{rec.evidence_id}", headers=self.headers)
            elapsed_ms = (time.perf_counter() - start) * 1000.0
            self.assertEqual(r.status_code, 200)
            latencies.append(elapsed_ms)

        mean_latency = sum(latencies) / len(latencies)
        print(f"\nDecision Evidence API mean latency: {mean_latency:.2f} ms (p95: {sorted(latencies)[int(0.95 * len(latencies))]:.2f} ms)")
        self.assertLess(mean_latency, 15.0, f"Mean latency {mean_latency:.2f}ms exceeds 15ms target")

