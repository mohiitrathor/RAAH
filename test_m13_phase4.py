    # -----------------------------------------------------------------
    # 10. Unauthenticated request returns 401
    # -----------------------------------------------------------------
    def test_10_unauthenticated_request_returns_401(self):
        """Missing or malformed authorization credentials must return HTTP 401."""
        prev_fallback = settings.dev_auth_fallback
        try:
            settings.dev_auth_fallback = False
            # 1. Missing token
            r_missing = self.client.get("/decision-evidence/incident/1")
            self.assertEqual(r_missing.status_code, 401)
            self.assertIn("WWW-Authenticate", r_missing.headers)

            # 2. Malformed token
            r_malformed = self.client.get(
                "/decision-evidence/incident/1",
                headers={"Authorization": "Bearer invalid-garbage-token"},
            )
            self.assertEqual(r_malformed.status_code, 401)

            # 3. Invalid signature
            fake_sig_token = create_test_token(
                role=Role.DISPATCHER,
                secret_key="some-different-secret-key-that-is-at-least-32-chars",
            )
            r_bad_sig = self.client.get(
                "/decision-evidence/incident/1",
                headers={"Authorization": f"Bearer {fake_sig_token}"},
            )
            self.assertEqual(r_bad_sig.status_code, 401)

            # 4. Expired token
            expired_token = create_test_token(
                role=Role.DISPATCHER,
                expires_delta=timedelta(seconds=-60),
            )
            r_exp = self.client.get(
                "/decision-evidence/incident/1",
                headers={"Authorization": f"Bearer {expired_token}"},
            )
            self.assertEqual(r_exp.status_code, 401)
        finally:
            settings.dev_auth_fallback = prev_fallback

