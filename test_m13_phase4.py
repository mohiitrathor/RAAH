    # -----------------------------------------------------------------
    # 7. Incident records have deterministic ordering
    # -----------------------------------------------------------------
    def test_07_incident_records_deterministic_ordering(self):
        """Incident records must be returned in deterministic chronological order."""
        rec1 = DecisionEvidenceRecord(
            decision_type=DecisionType.INITIAL_DISPATCH,
            action="DISPATCH_1",
            incident_id=42,
            sim_time=100,
            timestamp_iso="2026-09-07T10:00:00+00:00",
        )
        rec2 = DecisionEvidenceRecord(
            decision_type=DecisionType.HOSPITAL_REDIRECTION,
            action="REDIRECT_1",
            incident_id=42,
            sim_time=150,
            timestamp_iso="2026-09-07T10:05:00+00:00",
        )
        rec3 = DecisionEvidenceRecord(
            decision_type=DecisionType.INITIAL_DISPATCH,
            action="DISPATCH_PRE",
            incident_id=42,
            sim_time=50,
            timestamp_iso="2026-09-07T09:55:00+00:00",
        )

        # Record out of order
        evidence_store.record(rec1)
        evidence_store.record(rec2)
        evidence_store.record(rec3)

        resp = self.client.get("/decision-evidence/incident/42", headers=self.headers)
        self.assertEqual(resp.status_code, 200)
        records = resp.json()["records"]
        self.assertEqual(len(records), 3)

        sim_times = [r["evidence"]["sim_time"] for r in records]
        self.assertEqual(sim_times, [50, 100, 150], "Must sort chronologically by sim_time")

